    rot = math.degrees(math.atan2(P[1][1] - P[0][1], P[1][0] - P[0][0]))
    return {"r": [round(cx - w / 2, 1), round(cz - d / 2, 1), round(cx + w / 2, 1), round(cz + d / 2, 1)], "rot": round(rot, 1)}


